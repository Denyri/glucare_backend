-- 1. Table: knowledge_base_rules
CREATE TABLE IF NOT EXISTS `knowledge_base_rules` (
  `rule_id` VARCHAR(10) NOT NULL PRIMARY KEY,
  `category` VARCHAR(50) NOT NULL,
  `factor` VARCHAR(100) NOT NULL,
  `input_variable` VARCHAR(50) NOT NULL,
  `condition_operator` VARCHAR(10) NOT NULL,
  `threshold_value` DECIMAL(10,2) DEFAULT NULL,
  `threshold_unit` VARCHAR(30) DEFAULT NULL,
  `severity` ENUM('low', 'medium', 'high', 'critical') NOT NULL,
  `evidence_level` VARCHAR(20) NOT NULL,
  `base_priority_score` INT NOT NULL,
  `recommendation_template` TEXT NOT NULL,
  `action_template` TEXT NOT NULL,
  `default_initial_target` TEXT NOT NULL,
  `progress_metric` VARCHAR(100) NOT NULL,
  `safety_note` TEXT DEFAULT NULL,
  `is_referral_rule` TINYINT(1) DEFAULT 0,
  `referral_urgency` VARCHAR(20) DEFAULT 'none',
  `referral_text` TEXT DEFAULT NULL,
  `evidence_source` VARCHAR(150) NOT NULL,
  `evidence_year` INT NOT NULL,
  `evidence_doi_url` VARCHAR(255) DEFAULT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. Table: user_recommendations
CREATE TABLE IF NOT EXISTS `user_recommendations` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `user_id` INT NOT NULL,
  `analysis_id` INT DEFAULT NULL,
  `rule_id` VARCHAR(10) NOT NULL,
  `category` VARCHAR(50) NOT NULL,
  `priority_rank` TINYINT NOT NULL CHECK (`priority_rank` BETWEEN 1 AND 3),
  `priority_score` INT NOT NULL,
  `recommendation_text` TEXT NOT NULL,
  `recommended_action` TEXT NOT NULL,
  `initial_target` TEXT NOT NULL,
  `progress_metric` VARCHAR(100) NOT NULL,
  `status` ENUM('active', 'in_progress', 'completed', 'adjusted') DEFAULT 'active',
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_user_recommendations_user` (`user_id`),
  INDEX `idx_user_recommendations_rule` (`rule_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. Table: user_goals
CREATE TABLE IF NOT EXISTS `user_goals` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `user_id` INT NOT NULL,
  `recommendation_id` INT DEFAULT NULL,
  `category` VARCHAR(50) NOT NULL,
  `goal_title` VARCHAR(150) NOT NULL,
  `target_value` DECIMAL(10,2) NOT NULL,
  `current_value` DECIMAL(10,2) DEFAULT 0.00,
  `unit` VARCHAR(30) NOT NULL,
  `phase_number` TINYINT NOT NULL DEFAULT 1 CHECK (`phase_number` BETWEEN 1 AND 4),
  `start_date` DATE NOT NULL,
  `end_date` DATE NOT NULL,
  `status` ENUM('in_progress', 'achieved', 'adjusted', 'abandoned') DEFAULT 'in_progress',
  `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_user_goals_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

